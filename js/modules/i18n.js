let currentLang;
try { currentLang = localStorage.getItem('lang') || 'es'; } catch(e) { currentLang = 'es'; }

export function getTranslation(key) {
  try {
    return translations[currentLang][key] || null;
  } catch(e) { return null; }
}

export function setLanguage(lang) {
  try {
    currentLang = lang;
    try { localStorage.setItem('lang', lang); } catch(e) {}

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      const text = getTranslation(key);
      if (text !== null && text !== undefined) {
        el.innerHTML = text;
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.dataset.i18nPlaceholder;
      const text = getTranslation(key);
      if (text) el.placeholder = text;
    });

    document.querySelectorAll('[data-i18n-skill]').forEach(el => {
      const key = el.dataset.i18nSkill;
      const text = getTranslation(key);
      if (text) el.textContent = text;
    });

    updateExperienceDisplay();

    const allCertsToggleEl = document.getElementById('allCertsToggle');
    if (allCertsToggleEl) {
      const span = allCertsToggleEl.querySelector('span[data-i18n]');
      if (span) {
        const isOpen = allCertsToggleEl.getAttribute('aria-expanded') === 'true';
        span.textContent = getTranslation(isOpen ? 'certs.ocultar' : 'certs.ver-todos');
      }
    }

    const langToggle = document.getElementById('langToggle');
    if (langToggle) {
      langToggle.textContent = lang === 'es' ? 'EN' : 'ES';
      langToggle.setAttribute('aria-label', getTranslation(lang === 'es' ? 'lang.aria' : 'lang.aria.en'));
    }

    const submitBtn = document.getElementById('submitBtn');
    if (submitBtn && !submitBtn.disabled) {
      submitBtn.textContent = getTranslation('footer.form.submit');
    }

    const darkToggle = document.getElementById('darkToggle');
    if (darkToggle) {
      darkToggle.setAttribute('aria-label', getTranslation('dark.aria'));
    }

    document.documentElement.lang = getTranslation('html.lang') || (lang === 'es' ? 'es' : 'en');

    document.querySelectorAll('[data-i18n-content]').forEach(el => {
      el.setAttribute('content', getTranslation(el.dataset.i18nContent) || '');
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      const text = getTranslation(el.dataset.i18nAlt);
      if (text) el.alt = text;
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const text = getTranslation(el.dataset.i18nAria);
      if (text) el.setAttribute('aria-label', text);
    });

    const honeypotLabel = document.querySelector('.honeypot-field label');
    if (honeypotLabel) {
      honeypotLabel.textContent = getTranslation('honeypot.label');
    }

    document.querySelectorAll('[data-i18n-tag]').forEach(el => {
      const text = getTranslation(el.dataset.i18nTag);
      if (text) el.textContent = text;
    });

    updateCopyright();
  } catch(e) { console.error('Lang error:', e); }
}

export function updateCopyright() {
  const yearSpan = document.getElementById("current-year");
  const copyrightEl = document.getElementById("copyright-text");
  if (yearSpan && copyrightEl) {
    yearSpan.textContent = new Date().getFullYear();
    copyrightEl.textContent = `Ali Valentin Tovar Morales. ${getTranslation('footer.copyright')}`;
  }
}

export function calculateExperience(startDate) {
  const start = new Date(startDate);
  const now = new Date();

  let years = now.getFullYear() - start.getFullYear();
  let months = now.getMonth() - start.getMonth();

  if (months < 0) {
    years--;
    months += 12;
  }

  let result = "";
  if (years > 0) {
    result += years + (years === 1 ? getTranslation('exp.year_singular') : getTranslation('exp.year_plural'));
  }
  if (months > 0) {
    if (result !== "") result += getTranslation('exp.and');
    result += months + (months === 1 ? getTranslation('exp.month_singular') : getTranslation('exp.month_plural'));
  }

  return result || getTranslation('exp.zero_months');
}

export function updateExperienceDisplay() {
  const expElement = document.getElementById("brubank-experience");
  if (expElement) {
    const duration = calculateExperience("2021-04-01");
    expElement.textContent = duration;
  }
}

